#!/bin/bash
# gpu-mode.sh — three-state GPU profile switcher for Hybrid NVIDIA laptops.
#
#   integrated  Intel only; NVIDIA ICD not loaded → invisible to Vulkan.
#   hybrid      Intel default; both ICDs loaded; prime-run forces NVIDIA per-app.
#   nvidia      Only NVIDIA ICD loaded; everything renders on MX350.
#
# The dGPU (MX350-class) has no display outputs (the panel is wired to the
# iGPU), so "discrete" means global render offload, not display offload.
#
# VK_ICD_FILENAMES is the Vulkan device selector: it tells the loader which
# ICD JSON files to read. Setting it to intel_icd.json hides NVIDIA entirely
# from Vulkan — more reliable than __VK_LAYER_NV_optimus, which is only active
# when __NV_PRIME_RENDER_OFFLOAD=1 (see nvidia_layers.json enable_environment).
# In hybrid mode, prime-run sets offload=1 → the layer activates → NVIDIA_only
# filters to NVIDIA. So prime-run still works in hybrid without VK_ICD override.
#
# State:  ~/.local/state/omarchy/gpu-mode
# Hypr:   ~/.local/state/omarchy/toggles/hypr/gpu-mode.lua  (auto-loaded on reload)
#
# Environment is pushed through channels that actually work on a Lua-config
# Hyprland (hyprctl keyword env is dead — "keyword can't work with non-legacy
# parsers"):
#   1. systemctl --user set-environment  — systemd user env (uwsm-app / menu)
#   2. dbus-update-activation-environment  — D-Bus activation env
#   3. hl.env() in toggle lua              — Hyprland config env (on reload)
set -euo pipefail

STATE_DIR="$HOME/.local/state/omarchy"
STATE="$STATE_DIR/gpu-mode"
TOGGLE_DIR="$STATE_DIR/toggles/hypr"
TOGGLE="$TOGGLE_DIR/gpu-mode.lua"
ICD_DIR="/usr/share/vulkan/icd.d"

mkdir -p "$STATE_DIR" "$TOGGLE_DIR"

current_mode() {
  local v
  v="$(tr -d ' \n\r' <"$STATE" 2>/dev/null || true)"
  case "$v" in integrated|hybrid|nvidia) printf '%s' "$v" ;; *) printf 'hybrid' ;; esac
}

# Per-mode values.
# VK_ICD:  path to ICD json, or empty (unset → all ICDs loaded).
# PRIME:   __NV_PRIME_RENDER_OFFLOAD value (1=on, 0=off).
# GLX:     __GLX_VENDOR_LIBRARY_NAME (nvidia / mesa / empty=default).
# LIBVA:   LIBVA_DRIVER_NAME (nvidia / iHD).
mode_values() {
  case "$1" in
  nvidia)
    VK_ICD="$ICD_DIR/nvidia_icd.json"; PRIME=1; GLX=nvidia; LIBVA=nvidia ;;
  integrated)
    VK_ICD="$ICD_DIR/intel_icd.json";  PRIME=0; GLX=mesa;   LIBVA=iHD ;;
  hybrid | *)
    VK_ICD="";                          PRIME=0; GLX="";     LIBVA=iHD ;;
  esac
}

write_toggle() {
  mode_values "$1"
  cat >"$TOGGLE" <<LUA
-- generated by dan.gpu-mode ($1) — do not edit
hl.env("VK_ICD_FILENAMES", "$VK_ICD")
hl.env("__NV_PRIME_RENDER_OFFLOAD", "$PRIME")
hl.env("__GLX_VENDOR_LIBRARY_NAME", "$GLX")
hl.env("LIBVA_DRIVER_NAME", "$LIBVA")
LUA
}

apply_live_env() {
  mode_values "$1"
  if [ "$1" = "hybrid" ]; then
    # Hybrid = natural default: unset NVIDIA env vars so both GPUs are visible.
    # prime-run overrides per-app (offload=1 → optimus layer active → NVIDIA_only).
    systemctl --user unset-environment \
      VK_ICD_FILENAMES \
      __NV_PRIME_RENDER_OFFLOAD \
      __GLX_VENDOR_LIBRARY_NAME 2>/dev/null || true
    systemctl --user set-environment "LIBVA_DRIVER_NAME=iHD" 2>/dev/null || true
    dbus-update-activation-environment \
      "VK_ICD_FILENAMES=" \
      "__NV_PRIME_RENDER_OFFLOAD=" \
      "__GLX_VENDOR_LIBRARY_NAME=" \
      "LIBVA_DRIVER_NAME=iHD" 2>/dev/null || true
  else
    # nvidia / integrated: set all 4 vars through systemd + dbus.
    # hyprctl keyword env doesn't work with Lua config, so skip that channel.
    systemctl --user set-environment \
      "VK_ICD_FILENAMES=$VK_ICD" \
      "__NV_PRIME_RENDER_OFFLOAD=$PRIME" \
      "__GLX_VENDOR_LIBRARY_NAME=$GLX" \
      "LIBVA_DRIVER_NAME=$LIBVA" 2>/dev/null || true
    dbus-update-activation-environment \
      "VK_ICD_FILENAMES=$VK_ICD" \
      "__NV_PRIME_RENDER_OFFLOAD=$PRIME" \
      "__GLX_VENDOR_LIBRARY_NAME=$GLX" \
      "LIBVA_DRIVER_NAME=$LIBVA" 2>/dev/null || true
  fi
}

notify_mode() {
  local m="$1" msg
  case "$m" in
  integrated) msg="Intel only. Reopen apps from new terminal (Super+Enter)" ;;
  hybrid) msg="Intel default + prime-run. Reopen apps from new terminal" ;;
  nvidia) msg="All on NVIDIA. Reopen apps from new terminal (Super+Enter)" ;;
  esac
  if command -v omarchy-notification-send >/dev/null 2>&1; then
    omarchy-notification-send -u low "GPU: $m" "$msg" >/dev/null 2>&1 || true
  elif command -v notify-send >/dev/null 2>&1; then
    notify-send -u low "GPU: $m" "$msg" >/dev/null 2>&1 || true
  fi
}

case "${1:-get}" in
get | "")
  current_mode
  ;;
set)
  m="$(printf '%s' "${2:-}" | tr '[:upper:]' '[:lower:]')"
  case "$m" in integrated | hybrid | nvidia) : ;; *)
    echo "usage: gpu-mode.sh set {integrated|hybrid|nvidia}" >&2
    exit 1
    ;;
  esac
  printf '%s' "$m" >"$STATE"
  write_toggle "$m"
  apply_live_env "$m"
  hyprctl reload >/dev/null 2>&1 || true
  notify_mode "$m"
  printf '%s' "$m"
  # Restart shell so bar/launcher pick up the new env.
  setsid bash -c 'sleep 1 && omarchy restart shell' </dev/null >/dev/null 2>&1 &
  ;;
cycle)
  case "$(current_mode)" in
  integrated) nxt=hybrid ;;
  hybrid) nxt=nvidia ;;
  *) nxt=integrated ;;
  esac
  "$0" set "$nxt"
  ;;
--help | -h | help)
  echo "usage: gpu-mode.sh [get|set {integrated|hybrid|nvidia}|cycle]"
  ;;
*)
  echo "unknown subcommand: $1" >&2
  exit 1
  ;;
esac
