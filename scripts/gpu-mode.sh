#!/bin/bash
# gpu-mode.sh — three-state GPU profile switcher for Hybrid NVIDIA laptops.
#
#   integrated  Intel only; NVIDIA ICD not loaded.
#   hybrid      Both ICDs loaded; Intel default, prime-run forces NVIDIA.
#   nvidia      Only NVIDIA ICD loaded; everything renders on MX350.
#
# VK_ICD_FILENAMES is colon-separated. Empty string crashes the Vulkan loader,
# so hybrid lists both paths explicitly. prime-run activates the NVIDIA optimus
# layer (offload=1 → layer active → NVIDIA_only filter).
set -euo pipefail

STATE_DIR="$HOME/.local/state/omarchy"
STATE="$STATE_DIR/gpu-mode"
TOGGLE_DIR="$STATE_DIR/toggles/hypr"
TOGGLE="$TOGGLE_DIR/gpu-mode.lua"
ICD_DIR="/usr/share/vulkan/icd.d"

mkdir -p "$STATE_DIR" "$TOGGLE_DIR"

current_mode() {
  local v; v="$(tr -d ' \n\r' <"$STATE" 2>/dev/null || true)"
  case "$v" in integrated|hybrid|nvidia) printf '%s' "$v" ;; *) printf 'hybrid' ;; esac
}

mode_values() {
  case "$1" in
  nvidia)     VK_ICD="$ICD_DIR/nvidia_icd.json"; PRIME=1; GLX=nvidia; LIBVA=nvidia ;;
  integrated) VK_ICD="$ICD_DIR/intel_icd.json";  PRIME=0; GLX=mesa;   LIBVA=iHD ;;
  hybrid|*)   VK_ICD="$ICD_DIR/intel_icd.json:$ICD_DIR/nvidia_icd.json"; PRIME=0; GLX=""; LIBVA=iHD ;;
  esac
}

write_toggle() {
  mode_values "$1"
  cat >"$TOGGLE" <<LUA
-- generated by dan.gpu-mode ($1)
hl.env("VK_ICD_FILENAMES", "$VK_ICD")
hl.env("__NV_PRIME_RENDER_OFFLOAD", "$PRIME")
hl.env("__GLX_VENDOR_LIBRARY_NAME", "$GLX")
hl.env("LIBVA_DRIVER_NAME", "$LIBVA")
LUA
}

apply_live_env() {
  mode_values "$1"
  systemctl --user set-environment \
    "VK_ICD_FILENAMES=$VK_ICD" "__NV_PRIME_RENDER_OFFLOAD=$PRIME" \
    "__GLX_VENDOR_LIBRARY_NAME=$GLX" "LIBVA_DRIVER_NAME=$LIBVA" 2>/dev/null || true
  dbus-update-activation-environment \
    "VK_ICD_FILENAMES=$VK_ICD" "__NV_PRIME_RENDER_OFFLOAD=$PRIME" \
    "__GLX_VENDOR_LIBRARY_NAME=$GLX" "LIBVA_DRIVER_NAME=$LIBVA" 2>/dev/null || true
}

notify_mode() {
  local m="$1" msg
  case "$m" in
  integrated) msg="Intel only. Reopen apps from new terminal (Super+Enter)" ;;
  hybrid) msg="Intel default + prime-run. Reopen apps" ;;
  nvidia) msg="All on NVIDIA. Reopen apps from new terminal" ;;
  esac
  command -v omarchy-notification-send >/dev/null 2>&1 && omarchy-notification-send -u low "GPU: $m" "$msg" >/dev/null 2>&1 || \
  command -v notify-send >/dev/null 2>&1 && notify-send -u low "GPU: $m" "$msg" >/dev/null 2>&1 || true
}

case "${1:-get}" in
get|"") current_mode ;;
set)
  m="$(printf '%s' "${2:-}" | tr '[:upper:]' '[:lower:]')"
  case "$m" in integrated|hybrid|nvidia) :;; *) echo "usage: gpu-mode.sh set {integrated|hybrid|nvidia}" >&2; exit 1;; esac
  printf '%s' "$m" >"$STATE"
  write_toggle "$m"
  apply_live_env "$m"
  hyprctl reload >/dev/null 2>&1 || true
  notify_mode "$m"
  printf '%s' "$m"
  setsid bash -c 'sleep 1 && omarchy restart shell' </dev/null >/dev/null 2>&1 &
  ;;
cycle)
  case "$(current_mode)" in integrated) nxt=hybrid;; hybrid) nxt=nvidia;; *) nxt=integrated;; esac
  "$0" set "$nxt" ;;
*) echo "unknown: $1" >&2; exit 1 ;;
esac

