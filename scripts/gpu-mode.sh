#!/bin/bash
# gpu-mode.sh — three-state GPU profile switcher for Hybrid NVIDIA laptops.
#
#   integrated  Intel only; Vulkan layer hides NVIDIA, GLX stays on Mesa.
#   hybrid      Intel default; NVIDIA available per-app via prime-run.
#   nvidia      Everything renders on the dGPU via PRIME render offload.
#
# The MX350-class dGPU has no display outputs (the panel is wired to the iGPU),
# so "discrete" means global render offload, not display offload.
#
# State:  ~/.local/state/omarchy/gpu-mode
# Hypr:   ~/.local/state/omarchy/toggles/hypr/gpu-mode.lua  (auto-loaded on reload)
set -euo pipefail

STATE_DIR="$HOME/.local/state/omarchy"
STATE="$STATE_DIR/gpu-mode"
TOGGLE_DIR="$STATE_DIR/toggles/hypr"
TOGGLE="$TOGGLE_DIR/gpu-mode.lua"

mkdir -p "$STATE_DIR" "$TOGGLE_DIR"

current_mode() {
  local v
  v="$(tr -d ' \n\r' <"$STATE" 2>/dev/null || true)"
  case "$v" in integrated|hybrid|nvidia) printf '%s' "$v" ;; *) printf 'hybrid' ;; esac
}

write_toggle() {
  local m="$1"
  case "$m" in
  nvidia)
    cat >"$TOGGLE" <<'LUA'
-- generated by dan.gpu-mode (discrete) — global PRIME render offload
hl.env("__NV_PRIME_RENDER_OFFLOAD", "1")
hl.env("__VK_LAYER_NV_optimus", "NVIDIA_only")
hl.env("__GLX_VENDOR_LIBRARY_NAME", "nvidia")
hl.env("LIBVA_DRIVER_NAME", "nvidia")
hl.env("NVD_BACKEND", "direct")
LUA
    ;;
  integrated)
    cat >"$TOGGLE" <<'LUA'
-- generated by dan.gpu-mode (integrated) — iGPU only, dGPU bypassed
hl.env("__NV_PRIME_RENDER_OFFLOAD", "0")
hl.env("__VK_LAYER_NV_optimus", "non_NVIDIA_only")
hl.env("__GLX_VENDOR_LIBRARY_NAME", "")
hl.env("LIBVA_DRIVER_NAME", "iHD")
LUA
    ;;
  hybrid | *)
    cat >"$TOGGLE" <<'LUA'
-- generated by dan.gpu-mode (hybrid) — iGPU default, dGPU per-app via prime-run
hl.env("__NV_PRIME_RENDER_OFFLOAD", "0")
hl.env("__VK_LAYER_NV_optimus", "")
hl.env("__GLX_VENDOR_LIBRARY_NAME", "")
hl.env("LIBVA_DRIVER_NAME", "iHD")
LUA
    ;;
  esac
}

notify_mode() {
  local m="$1" msg
  case "$m" in
  integrated) msg="Intel only — dGPU bypassed (power saving)" ;;
  hybrid) msg="Intel default — dGPU via prime-run" ;;
  nvidia) msg="Discrete — all apps render on NVIDIA" ;;
  esac
  if command -v omarchy-notification-send >/dev/null 2>&1; then
    omarchy-notification-send -u low "GPU: $m" "$msg" >/dev/null 2>&1 || true
  elif command -v notify-send >/dev/null 2>&1; then
    notify-send -u low "GPU: $m" "$msg" >/dev/null 2>&1 || true
  fi
}

# Apply env to the running compositor as well as to the Lua file. hl.env() is
# only read at config load time in some Hyprland builds, so hyprctl setenv
# covers reloads that skip the module.
apply_live_env() {
  local m="$1"
  case "$m" in
  nvidia)
    hyprctl setenv __NV_PRIME_RENDER_OFFLOAD 1 >/dev/null 2>&1 || true
    hyprctl setenv __VK_LAYER_NV_optimus NVIDIA_only >/dev/null 2>&1 || true
    hyprctl setenv __GLX_VENDOR_LIBRARY_NAME nvidia >/dev/null 2>&1 || true
    hyprctl setenv LIBVA_DRIVER_NAME nvidia >/dev/null 2>&1 || true
    ;;
  integrated)
    hyprctl setenv __NV_PRIME_RENDER_OFFLOAD 0 >/dev/null 2>&1 || true
    hyprctl setenv __VK_LAYER_NV_optimus non_NVIDIA_only >/dev/null 2>&1 || true
    hyprctl setenv __GLX_VENDOR_LIBRARY_NAME "" >/dev/null 2>&1 || true
    hyprctl setenv LIBVA_DRIVER_NAME iHD >/dev/null 2>&1 || true
    ;;
  hybrid | *)
    hyprctl setenv __NV_PRIME_RENDER_OFFLOAD 0 >/dev/null 2>&1 || true
    hyprctl setenv __VK_LAYER_NV_optimus "" >/dev/null 2>&1 || true
    hyprctl setenv __GLX_VENDOR_LIBRARY_NAME "" >/dev/null 2>&1 || true
    hyprctl setenv LIBVA_DRIVER_NAME iHD >/dev/null 2>&1 || true
    ;;
  esac
  dbus-update-activation-environment --systemd __NV_PRIME_RENDER_OFFLOAD __VK_LAYER_NV_optimus __GLX_VENDOR_LIBRARY_NAME LIBVA_DRIVER_NAME >/dev/null 2>&1 || true
}

case "${1:-get}" in
get | "")
  current_mode
  ;;
set)
  m="$(printf '%s' "${2:-}" | tr '[:upper:]' '[:lower:]')"
  case "$m" in integrated | hybrid | nvidia) : ;; *)
    echo "usage: gpu-mode.sh set {integrated|hybrid|nvidia}" >&2
    exit 1
    ;;
  esac
  printf '%s' "$m" >"$STATE"
  write_toggle "$m"
  apply_live_env "$m"
  hyprctl reload >/dev/null 2>&1 || true
  # Refresh every bar instance of the widget (best-effort; harmless if absent).
  omarchy-shell dan.gpu-mode refresh >/dev/null 2>&1 || true
  notify_mode "$m"
  printf '%s' "$m"
  ;;
cycle)
  case "$(current_mode)" in
  integrated) nxt=hybrid ;;
  hybrid) nxt=nvidia ;;
  *) nxt=integrated ;;
  esac
  "$0" set "$nxt"
  ;;
--help | -h | help)
  echo "usage: gpu-mode.sh [get|set {integrated|hybrid|nvidia}|cycle]"
  ;;
*)
  echo "unknown subcommand: $1" >&2
  exit 1
  ;;
esac
