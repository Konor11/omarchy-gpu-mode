#!/bin/bash
# gpu-mode.sh — three-state GPU profile switcher for Hybrid NVIDIA laptops.
#
#   integrated  Intel only; Vulkan layer hides NVIDIA, GLX forced to Mesa.
#   hybrid      Intel default; NVIDIA available per-app via prime-run.
#   nvidia      Everything renders on the dGPU via PRIME render offload.
#
# The dGPU (MX350-class) has no display outputs (the panel is wired to the
# iGPU), so "discrete" means global render offload, not display offload.
#
# State:  ~/.local/state/omarchy/gpu-mode
# Hypr:   ~/.local/state/omarchy/toggles/hypr/gpu-mode.lua  (auto-loaded on reload)
#
# Environment is pushed through THREE channels so every launch path picks it
# up live (no reboot, no re-login):
#   1. hyprctl keyword env   — Hyprland's own env (directly dispatched apps)
#   2. systemctl --user      — systemd user env (uwsm-app / menu-launched apps)
#   3. dbus-update-activation — D-Bus activation env (dbus-activated apps)
# hl.env() in the toggle lua is unreliable for OVERWRITING existing vars on
# reload, so the three live channels are what actually reach new processes.
set -euo pipefail

STATE_DIR="$HOME/.local/state/omarchy"
STATE="$STATE_DIR/gpu-mode"
TOGGLE_DIR="$STATE_DIR/toggles/hypr"
TOGGLE="$TOGGLE_DIR/gpu-mode.lua"

mkdir -p "$STATE_DIR" "$TOGGLE_DIR"

current_mode() {
  local v
  v="$(tr -d ' \n\r' <"$STATE" 2>/dev/null || true)"
  case "$v" in integrated|hybrid|nvidia) printf '%s' "$v" ;; *) printf 'hybrid' ;; esac
}

# Per-mode values: PRIME offload flag, GLX vendor, Vulkan layer filter, VA-API driver.
mode_values() {
  case "$1" in
  nvidia)     PRIME=1; GLX=nvidia; VK=NVIDIA_only;     LIBVA=nvidia ;;
  integrated) PRIME=0; GLX=mesa;   VK=non_NVIDIA_only; LIBVA=iHD ;;
  hybrid | *) PRIME=0; GLX=mesa;   VK=all;             LIBVA=iHD ;;
  esac
}

# Persist across reboots: the toggles dir is re-loaded on every hyprctl reload.
write_toggle() {
  mode_values "$1"
  cat >"$TOGGLE" <<LUA
-- generated by dan.gpu-mode ($1) — do not edit
hl.env("__NV_PRIME_RENDER_OFFLOAD", "$PRIME")
hl.env("__GLX_VENDOR_LIBRARY_NAME", "$GLX")
hl.env("__VK_LAYER_NV_optimus", "$VK")
hl.env("LIBVA_DRIVER_NAME", "$LIBVA")
LUA
}

# Push env through all three live channels. Silent: the widget reads this
# script's stdout for the mode name, so env commands must not print anything.
apply_live_env() {
  mode_values "$1"
  # 1. Hyprland env (directly dispatched apps, keybind-launched terminals)
  hyprctl keyword env __NV_PRIME_RENDER_OFFLOAD,"$PRIME" >/dev/null 2>&1 || true
  hyprctl keyword env __GLX_VENDOR_LIBRARY_NAME,"$GLX" >/dev/null 2>&1 || true
  hyprctl keyword env __VK_LAYER_NV_optimus,"$VK" >/dev/null 2>&1 || true
  hyprctl keyword env LIBVA_DRIVER_NAME,"$LIBVA" >/dev/null 2>&1 || true
  # 2. systemd user env — THE channel for uwsm-app / menu-launched apps on Omarchy
  systemctl --user set-environment \
    "__NV_PRIME_RENDER_OFFLOAD=$PRIME" \
    "__GLX_VENDOR_LIBRARY_NAME=$GLX" \
    "__VK_LAYER_NV_optimus=$VK" \
    "LIBVA_DRIVER_NAME=$LIBVA" >/dev/null 2>&1 || true
  # 3. D-Bus activation env — for dbus-activated services (Flatpak, portals, etc.)
  dbus-update-activation-environment \
    "__NV_PRIME_RENDER_OFFLOAD=$PRIME" \
    "__GLX_VENDOR_LIBRARY_NAME=$GLX" \
    "__VK_LAYER_NV_optimus=$VK" \
    "LIBVA_DRIVER_NAME=$LIBVA" >/dev/null 2>&1 || true
}

notify_mode() {
  local m="$1" msg
  case "$m" in
  integrated) msg="Intel only — dGPU bypassed (power saving)" ;;
  hybrid) msg="Intel default — dGPU via prime-run" ;;
  nvidia) msg="Discrete — all apps render on NVIDIA" ;;
  esac
  if command -v omarchy-notification-send >/dev/null 2>&1; then
    omarchy-notification-send -u low "GPU: $m" "$msg" >/dev/null 2>&1 || true
  elif command -v notify-send >/dev/null 2>&1; then
    notify-send -u low "GPU: $m" "$msg" >/dev/null 2>&1 || true
  fi
}

case "${1:-get}" in
get | "")
  current_mode
  ;;
set)
  m="$(printf '%s' "${2:-}" | tr '[:upper:]' '[:lower:]')"
  case "$m" in integrated | hybrid | nvidia) : ;; *)
    echo "usage: gpu-mode.sh set {integrated|hybrid|nvidia}" >&2
    exit 1
    ;;
  esac
  printf '%s' "$m" >"$STATE"
  write_toggle "$m"
  apply_live_env "$m"
  hyprctl reload >/dev/null 2>&1 || true
  notify_mode "$m"
  printf '%s' "$m"
  ;;
cycle)
  case "$(current_mode)" in
  integrated) nxt=hybrid ;;
  hybrid) nxt=nvidia ;;
  *) nxt=integrated ;;
  esac
  "$0" set "$nxt"
  ;;
--help | -h | help)
  echo "usage: gpu-mode.sh [get|set {integrated|hybrid|nvidia}|cycle]"
  ;;
*)
  echo "unknown subcommand: $1" >&2
  exit 1
  ;;
esac
